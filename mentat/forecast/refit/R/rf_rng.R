# Random draws of the wild cluster bootstrap, reproducing the Python pipeline's numpy stream bit for bit.
#
# estimate.py draws the Webb weights with
#   rng = np.random.default_rng(np.random.SeedSequence([seed, crc32(test id), crc32(coefficient)[, crc32(unit)]]))
#   V = rng.choice(WEBB, size=(B, G))
# This file reimplements that chain in base R, so the R port draws the same weight matrix as Python:
#   * zlib CRC-32 of the UTF-8 text parts (sgs_crc32);
#   * numpy SeedSequence (entropy -> 4-word pool -> generate_state), numpy/random/bit_generator.pyx;
#   * PCG64 (128-bit LCG, multiplier 0x2360ED051FC65DA44385DF649FCCF645, XSL-RR output), numpy/random/src/pcg64;
#   * Generator.choice(a, size, replace=True, p=None) = a[integers(0, 6, size)]; integers() uses Lemire's bounded
#     method on the 32-bit halves of the 64-bit outputs (low half first), numpy/random/src/distributions.
# All arithmetic is exact in doubles: 32-bit words are split into 16-bit halves and 128-bit states are 8 limbs of
# 16 bits (least significant first). The state sequence is generated by repeated doubling (s_{k+m} = A_m s_k + C_m),
# so a B x G draw matrix costs O(log(B G)) vectorised steps.
# tests/testthat/test_rng.R checks this module against reference values written by numpy 2.4.6.

SGS_WEBB <- c(-sqrt(1.5), -1.0, -sqrt(0.5), sqrt(0.5), 1.0, sqrt(1.5))

.TWO16 <- 65536
.TWO32 <- 4294967296

# ---- 32-bit words (doubles in [0, 2^32)) ------------------------------------------------------------------------

.u32_split <- function(a) {
  lo <- a %% .TWO16
  list(hi = (a - lo) / .TWO16, lo = lo)
}

.u32_mul <- function(a, b) {  # a * b mod 2^32
  A <- .u32_split(a)
  B <- .u32_split(b)
  lo <- A$lo * B$lo
  mid <- (A$hi * B$lo + A$lo * B$hi) %% .TWO16
  (lo + mid * .TWO16) %% .TWO32
}

.u32_xor <- function(a, b) {
  A <- .u32_split(a)
  B <- .u32_split(b)
  bitwXor(as.integer(A$hi), as.integer(B$hi)) * .TWO16 + bitwXor(as.integer(A$lo), as.integer(B$lo))
}

.u32_shr16 <- function(a) floor(a / .TWO16)

# ---- zlib CRC-32 ------------------------------------------------------------------------------------------------

.sgs_crc_table <- local({
  tab <- numeric(256)
  for (n in 0:255) {
    c <- n
    for (k in 1:8) {
      c <- if (c %% 2 == 1) .u32_xor(3988292384, floor(c / 2)) else floor(c / 2)  # 0xEDB88320
    }
    tab[n + 1] <- c
  }
  tab
})

# zlib.crc32(str(x).encode("utf-8")) as a double in [0, 2^32).
sgs_crc32 <- function(x) {
  bytes <- as.integer(charToRaw(enc2utf8(as.character(x))))
  crc <- 4294967295
  for (b in bytes) {
    idx <- bitwXor(as.integer(crc %% 256), b)
    crc <- .u32_xor(.sgs_crc_table[idx + 1], floor(crc / 256))
  }
  .u32_xor(crc, 4294967295)
}

# ---- numpy SeedSequence -----------------------------------------------------------------------------------------

.SS_INIT_A <- 1135663077   # 0x43b0d7e5
.SS_MULT_A <- 2468251765   # 0x931e8875
.SS_INIT_B <- 2337405405   # 0x8b51f9dd
.SS_MULT_B <- 1492356589   # 0x58f38ded
.SS_MIX_L <- 3389127133    # 0xca01f9dd
.SS_MIX_R <- 1232336661    # 0x4973f715

# One non-negative integer (< 2^53) -> its little-endian 32-bit words (numpy _int_to_uint32_array).
.ss_words <- function(n) {
  if (n == 0) return(0)
  out <- numeric(0)
  while (n > 0) {
    w <- n %% .TWO32
    out <- c(out, w)
    n <- (n - w) / .TWO32
  }
  out
}

# numpy SeedSequence(entropy).pool (pool size 4); entropy = vector of non-negative integers.
sgs_seedseq_pool <- function(entropy) {
  ent <- unlist(lapply(entropy, .ss_words))
  hc <- .SS_INIT_A
  hashmix <- function(value) {
    value <- .u32_xor(value, hc)
    hc <<- .u32_mul(hc, .SS_MULT_A)
    value <- .u32_mul(value, hc)
    .u32_xor(value, .u32_shr16(value))
  }
  mix <- function(x, y) {
    r <- (.u32_mul(.SS_MIX_L, x) - .u32_mul(.SS_MIX_R, y)) %% .TWO32
    .u32_xor(r, .u32_shr16(r))
  }
  pool <- numeric(4)
  for (i in 1:4) pool[i] <- hashmix(if (i <= length(ent)) ent[i] else 0)
  for (s in 1:4) for (d in 1:4) if (s != d) pool[d] <- mix(pool[d], hashmix(pool[s]))
  if (length(ent) > 4) for (s in 5:length(ent)) for (d in 1:4) pool[d] <- mix(pool[d], hashmix(ent[s]))
  pool
}

# SeedSequence.generate_state(n_words, np.uint32) from a pool.
sgs_seedseq_state32 <- function(pool, n_words) {
  hc <- .SS_INIT_B
  out <- numeric(n_words)
  for (i in seq_len(n_words)) {
    v <- pool[((i - 1) %% length(pool)) + 1]
    v <- .u32_xor(v, hc)
    hc <- .u32_mul(hc, .SS_MULT_B)
    v <- .u32_mul(v, hc)
    out[i] <- .u32_xor(v, .u32_shr16(v))
  }
  out
}

# ---- 128-bit arithmetic on 16-bit limbs -------------------------------------------------------------------------

.limbs_of_u32 <- function(w) c(w %% .TWO16, floor(w / .TWO16))

.carry128 <- function(R) {
  carry <- 0
  for (k in 1:8) {
    v <- R[, k] + carry
    carry <- floor(v / .TWO16)
    R[, k] <- v - carry * .TWO16
  }
  R
}

.mul128 <- function(S, a) {  # S: n x 8 limb matrix; a: 8 limbs; S * a mod 2^128
  R <- matrix(0, nrow(S), 8)
  for (k in 1:8) {
    acc <- 0
    for (i in 1:k) acc <- acc + S[, i] * a[k - i + 1]
    R[, k] <- acc
  }
  .carry128(R)
}

.add128 <- function(S, c) .carry128(S + matrix(c, nrow(S), 8, byrow = TRUE))

.PCG_MULT <- c(0xF645, 0x9FCC, 0xDF64, 0x4385, 0x5DA4, 0x1FC6, 0xED05, 0x2360)

# PCG64 as seeded by numpy's default_rng(SeedSequence(entropy)): list(state, inc) as 8-limb vectors.
sgs_pcg64_seed <- function(entropy) {
  st <- sgs_seedseq_state32(sgs_seedseq_pool(entropy), 8)  # generate_state(4, uint64): little-endian word pairs
  # initstate = u64[0] << 64 | u64[1]; initseq = u64[2] << 64 | u64[3]; u64[j] = st[2j+1] + st[2j+2] * 2^32
  initstate <- c(.limbs_of_u32(st[3]), .limbs_of_u32(st[4]), .limbs_of_u32(st[1]), .limbs_of_u32(st[2]))
  initseq <- c(.limbs_of_u32(st[7]), .limbs_of_u32(st[8]), .limbs_of_u32(st[5]), .limbs_of_u32(st[6]))
  dbl <- initseq * 2                                     # inc = (initseq << 1) | 1, mod 2^128
  inc <- dbl %% .TWO16 + c(1, floor(dbl[-8] / .TWO16))
  inc <- as.vector(.carry128(matrix(inc, 1)))
  s <- matrix(inc, 1)                                    # state = 0; step -> inc
  s <- .add128(s, initstate)                             # state += initstate
  s <- .add128(.mul128(s, .PCG_MULT), inc)               # step
  list(state = as.vector(s), inc = inc)
}

# The next n states after the seeded state (rows s_1 .. s_n).
.pcg64_states <- function(seeded, n) {
  S <- .add128(.mul128(matrix(seeded$state, 1), .PCG_MULT), seeded$inc)
  A <- .PCG_MULT
  C <- seeded$inc
  while (nrow(S) < n) {
    S <- rbind(S, .add128(.mul128(S, A), C))
    C <- as.vector(.add128(.mul128(matrix(C, 1), A), C))  # C_2m = A_m C_m + C_m
    A <- as.vector(.mul128(matrix(A, 1), A))              # A_2m = A_m^2
  }
  S[seq_len(n), , drop = FALSE]
}

# XSL-RR output of each state row: n x 4 limbs (16 bits each, least significant first) of the 64-bit output.
.pcg64_output <- function(S) {
  n <- nrow(S)
  X <- matrix(0, n, 4)
  for (i in 1:4) X[, i] <- bitwXor(as.integer(S[, i]), as.integer(S[, i + 4]))
  r <- floor(S[, 8] / 1024)  # state >> 122
  q <- r %/% 16
  s <- r %% 16
  rows <- seq_len(n)
  Y <- matrix(0, n, 4)
  for (i in 0:3) Y[, i + 1] <- X[cbind(rows, ((i + q) %% 4) + 1)]
  p <- 2^s
  Z <- matrix(0, n, 4)
  for (i in 0:3) {
    nxt <- Y[, ((i + 1) %% 4) + 1]
    Z[, i + 1] <- floor(Y[, i + 1] / p) + (nxt * (.TWO16 / p)) %% .TWO16
  }
  Z
}

# default_rng(SeedSequence(entropy)).bit_generator.random_raw(n) as lower-case hex strings (tests).
sgs_pcg64_raw_hex <- function(entropy, n) {
  Z <- .pcg64_output(.pcg64_states(sgs_pcg64_seed(entropy), n))
  apply(Z, 1, function(z) sub("^0+(?=.)", "", paste(sprintf("%04x", as.integer(rev(z))), collapse = ""), perl = TRUE))
}

# Indices 0..5 of default_rng(SeedSequence(entropy)).integers(0, 6, size = n).
sgs_numpy_integers6 <- function(entropy, n) {
  seeded <- sgs_pcg64_seed(entropy)
  extra <- 64
  repeat {
    Z <- .pcg64_output(.pcg64_states(seeded, ceiling((n + extra) / 2)))
    u <- as.vector(rbind(Z[, 1] + Z[, 2] * .TWO16, Z[, 3] + Z[, 4] * .TWO16))  # low half first, then high
    m <- u * 6
    idx <- floor(m / .TWO32)
    idx <- idx[(m - idx * .TWO32) >= 4]  # Lemire rejection: leftover < (2^32 - 1 - 5) %% 6 = 4 is redrawn
    if (length(idx) >= n) return(idx[seq_len(n)])
    extra <- extra * 16
  }
}

# Entropy of estimate.seed_for(seed, *parts) = [seed, crc32(str(part)), ...].
sgs_seed_entropy <- function(seed, ...) {
  parts <- as.character(c(...))
  c(as.numeric(seed), vapply(parts, sgs_crc32, 0, USE.NAMES = FALSE))
}

# estimate.webb_draws: all 6^G weight vectors (itertools.product order: last cluster fastest) when 6^G <= B, else
# rng.choice(WEBB, size = (B, G)), filled row by row. Returns list(V = draws x clusters matrix, enumerated).
sgs_webb_draws <- function(G, B, entropy) {
  if (6^G <= B) {
    r <- seq_len(6^G) - 1
    V <- matrix(0, 6^G, G)
    for (g in seq_len(G)) V[, g] <- SGS_WEBB[(r %/% 6^(G - g)) %% 6 + 1]
    return(list(V = V, enumerated = TRUE))
  }
  idx <- sgs_numpy_integers6(entropy, B * G)
  list(V = matrix(SGS_WEBB[idx + 1], nrow = B, ncol = G, byrow = TRUE), enumerated = FALSE)
}
