script <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE)[[1L]])
root <- normalizePath(file.path(dirname(script), ".."), winslash = "/")
source(file.path(root, "R", "paths.R"))
test_root <- tempfile("mentat-report-directory-")
dir.create(test_root)
configured <- file.path(test_root, "published"); dir.create(configured)
isolated <- file.path(test_root, "isolated"); dir.create(isolated)
config_root <- file.path(test_root, "project"); dir.create(config_root)
dir.create(file.path(config_root, "config"))
writeLines(jsonlite::toJSON(list(schema_version=1L, directory=normalizePath(configured,winslash="/")),auto_unbox=TRUE),
  file.path(config_root,"config","report-directory.json"))
prior <- Sys.getenv("MENTAT_REPORT_DIRECTORY", unset=NA_character_)
Sys.unsetenv("MENTAT_REPORT_DIRECTORY")
stopifnot(identical(mentat_report_directory(config_root), normalizePath(configured,winslash="/")))
Sys.setenv(MENTAT_REPORT_DIRECTORY=isolated)
paths <- mentat_paths(file.path(test_root,"data"))
stopifnot(identical(paths$reports,normalizePath(isolated,winslash="/")),
          identical(paths$database,file.path(paths$root,"mentat.db")),
          identical(mentat_report_directory(config_root),paths$reports))
Sys.setenv(MENTAT_REPORT_DIRECTORY=file.path(test_root,"unavailable"))
stopifnot(inherits(try(mentat_report_directory(config_root),silent=TRUE),"try-error"))
Sys.setenv(MENTAT_REPORT_DIRECTORY="relative-path")
stopifnot(inherits(try(mentat_report_directory(config_root),silent=TRUE),"try-error"))
if (is.na(prior)) Sys.unsetenv("MENTAT_REPORT_DIRECTORY") else Sys.setenv(MENTAT_REPORT_DIRECTORY=prior)
unlink(test_root,recursive=TRUE)
cat("test_report_directory: PASS\n")
