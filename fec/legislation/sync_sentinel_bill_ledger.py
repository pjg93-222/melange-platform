def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def decay_weight(congress):
    """Per-Congress evidence weight -- the same rule legacy archive rows carry.

    ``congress_bills_archive_*.xlsx`` stores DecayWeight = congress_decay(Congress)
    (119 -> 1.0, 118 -> 0.8, 117 -> 0.64), which is the frozen production schedule
    audit_legislation_decay_propagation enforces.  Sentinel rows previously shipped
    a literal 1.0, scoring an old Congress at full strength.  A row with no
    parseable Congress gets a blank cell rather than a fabricated weight.
    """
    try:
        return BR.congress_decay(congress)
    except (TypeError, ValueError):
        return ""


def load_ndjson(path: Path) -> list[dict]:
    rows = []
    if not path.is_file():
        return rows
    with path.open(encoding="utf-8") as stream:
        for number, line in enumerate(stream, 1):
            if not line.strip():
                continue
            value = json.loads(line)
            if not isinstance(value, dict):
                raise RuntimeError(f"{path}:{number}: row is not an object")
            rows.append(value)
    return rows


def load_supplemental_adjudications(path: Path | None = None) -> tuple[list[dict], dict]:
    """Read the lane-owned adjudication overlay and describe it for the receipt.

    ABSENCE IS A CLEAN SKIP -- the file is optional and a box without it must
    behave exactly as it did before this source existed.  A file that IS present
    is held to the decision schema: every row needs the greenlit-decision schema
    tag, a non-empty canonical_key and an integration_state, and no canonical_key
    may appear twice.  A malformed overlay raises rather than silently dropping a
    ratified decision on the floor.
    """
    target = SUPPLEMENTAL_ADJUDICATIONS if path is None else path
    block = {
        "path": str(target), "sha256": None, "rows": 0,
        "applied": 0, "collisions": 0, "collision_keys": [],
    }
    if not target.is_file():
        return [], block
    rows = load_ndjson(target)
    seen = set()
    for ordinal, row in enumerate(rows, 1):
        if row.get("schema") != ADJUDICATION_SCHEMA:
            raise RuntimeError("%s: row %d has schema %r, expected %r"
                               % (target, ordinal, row.get("schema"), ADJUDICATION_SCHEMA))
        if not str(row.get("canonical_key") or "").strip():
            raise RuntimeError("%s: row %d has no canonical_key" % (target, ordinal))
        if not str(row.get("integration_state") or "").strip():
            raise RuntimeError("%s: row %d has no integration_state" % (target, ordinal))
        key = str(row.get("canonical_key"))
        if key in seen:
            raise RuntimeError("%s: row %d repeats canonical_key %r" % (target, ordinal, key))
        seen.add(key)
    block["sha256"] = sha256(target)
    block["rows"] = len(rows)
    return rows, block


def merge_adjudications(frozen: list[dict], supplemental: list[dict]) -> tuple[list[dict], dict]:
    """Overlay lane-owned decisions onto the frozen ledger.  THE FROZEN LEDGER WINS.

    build_plan() folds its adjudication list into a dict keyed by canonical_key, so a
    later row silently replaces an earlier one.  A supplemental row must never be able
    to overwrite a ratified 2026-07-28 decision that way, so colliding rows are dropped
    here and counted for the receipt.  With no supplemental rows the returned list is
    the frozen ledger unchanged, in its original order.
    """
    taken = {str(row.get("canonical_key")) for row in frozen if row.get("canonical_key")}
    applied = []
    collisions = []
    for row in supplemental:
        key = str(row.get("canonical_key"))
        if key in taken:
            collisions.append(key)
            continue
        applied.append(row)
    return list(frozen) + applied, {
        "applied": len(applied),
        "collisions": len(collisions),
        "collision_keys": sorted(set(collisions))[:50],
    }


def stable_json_sha256(value) -> str:
    payload = json.dumps(
        value, sort_keys=True, ensure_ascii=False, separators=(",", ":")
    ).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def _field(row: dict, *names, default=""):
    for name in names:
        if name in row and row.get(name) is not None:
            return row.get(name)
    return default


def normalized_role(value) -> str:
    role = BR.canonical_role(value)
    if role == "original-cosponsor":
        return "original"
    if role in ("cosponsor", "sponsor"):
        return role
    raise RuntimeError(f"verified row has inadmissible role: {value}")


def normalized_areas(row: dict) -> list[str]:
    """Return one deterministic, duplicate-free category list for a membership.

    The durable history is intentionally member-level.  Category expansion is a
    workbook-view concern, so a repeated verifier row cannot duplicate an
    interaction and a later category addition grows the existing membership.
    """
    if "areas" in row:
        raw = row.get("areas")
        values = [raw] if isinstance(raw, str) else list(raw or [])
    else:
        values = [_field(row, "area", "Section")]
    unique = {}
    for value in values:
        text = " ".join(str(value or "").split())
        canonical = BR.canonical_category(text) or text
        unique.setdefault(canonical.casefold(), canonical)
    if not unique:
        unique[""] = ""
    return [unique[key] for key in sorted(unique)]


def membership_key(row: dict) -> str:
    repository_key = str(_field(row, "repository_key", "Canonical Bill ID")).strip().lower()
    bioguide = str(_field(row, "bioguide", "Bioguide")).strip().upper()
    if not repository_key:
        raise RuntimeError("verified history row has no canonical repository key")
    if not bioguide:
        raise RuntimeError(f"verified history row {repository_key} has no bioguide")
    role = normalized_role(_field(row, "role", "Role"))
    # Categories do not belong in this key.  One accepted person/bill/role is
    # stored once; its sorted category set expands deterministically at build time.
    return "smh1:" + stable_json_sha256([repository_key, bioguide, role])


