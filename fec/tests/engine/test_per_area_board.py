def roster_baseline():
    """The factor artifact's own baseline. Read, never typed: primacy_factors.py
    recomputes it every chain run (0.486619 on 2026-09-15, 0.481361 on 09-17)."""
    with open(_FACTORS, encoding='utf-8') as handle:
        constants = (json.load(handle).get('_constants') or {})
    value = constants.get('roster_baseline')
    if value is None:
        raise AssertionError('primacy_factors.json carries no roster_baseline')
    return float(value)


def grade(as_of=None, **overrides):
    """Build the grade from the live inputs once per (as_of, overrides)."""
    as_of = as_of or LIVE_AS_OF
    key = (as_of, tuple(sorted(overrides.items())))
    if key in _CACHE:
        return _CACHE[key]
    path = lambda *parts: os.path.join(ROOT, *parts)
    roster = PAG.load_roster(path('data', 'engine', 'congestion.json'))
    scored = PAG.load_pct_members(path('ranks_python.json'))
    factored = PAG.load_primacy_members(path('data', 'engine', 'primacy_factors.json'))
    rankable = [member for member in sorted(roster)
                if member in scored and member in factored]
    from collections import Counter
    stats = Counter()
    acts = PAG.load_acts(path('legislation_routing_audit.json'), stats)
    cells = PAG.load_cu_cells(path('data', 'lobbying', 'industry_axes.ndjson'))
    spine = PAG.read_service_spine(path(PAG.REFERENCE_DIR))
    votes, _counts = PAG.load_signed_votes(path('vote_category_lean.json'))
    proportion, items, weights, _receipt = PAG.load_method_inputs(roster, ROOT)
    result = PAG.build(roster, acts, cells, spine, votes, proportion, items,
                       rankable, as_of, beneficiary_weights=weights, **overrides)
    _CACHE[key] = (roster, rankable, result, stats, cells, items)
    return _CACHE[key]


def seated(result, rankable, *, gate=True):
    """Seat the P1 product exactly as tier_util does, from a built grade."""
    factors = TU.load_primacy_ranked(ROOT)
    multiplier = {member: TU.PER_AREA_PURITY_SHARE
                  + (1.0 - TU.PER_AREA_PURITY_SHARE)
                  * result['grade_percentile'][member] for member in rankable}
    if TU.PRIMACY_GRADE_FORM == 'deviation':   # RE-1 G1, the shipped default
        base = TU.load_primacy_baseline(ROOT)
        raw = {member: (base + (factors[member] - base) * multiplier[member]
                        if factors[member] >= base else factors[member])
               for member in rankable}
    else:
        raw = {member: factors[member] * multiplier[member]
               for member in rankable}
    percentile = TU.within_chamber_percentile(raw, result['chamber_of'])
    order = sorted(rankable,
                   key=lambda member: (-percentile[member], -raw[member], member))
    minimum_slots = {}
    if gate:
        minimum_slots = TU.evidence_slot_floors(
            order, TU.load_primacy_cu_credit(ROOT), exempt=set(TU.load_tier_overrides()))
    order, _detail = TU.apply_conduct_ladder(order, TU.load_open_breaches(ROOT),
                                             TU.load_delivery_credit(ROOT),
                                             minimum_slots=minimum_slots)
    return order


class PercentileConvention(unittest.TestCase):
    """The board and the producer must share ONE percentile, and it must be the
    repo's. Three implementations exist; this pins them to each other."""

    def probe(self):
        # 400 keys with heavy ties -- ties are where first-tie conventions differ.
        return {'m%03d' % index: float(index % 17) for index in range(400)}

    def test_producer_matches_board(self):
        probe = self.probe()
        self.assertEqual(PAG.percentrank(probe), TU._percentrank(probe))

    def test_producer_matches_effectiveness_integration(self):
        probe = self.probe()
        self.assertEqual(PAG.percentrank(probe), EI.percentiles(probe))

    def test_within_chamber_partitions(self):
        values = {'a': 1.0, 'b': 2.0, 'c': 3.0, 'd': 4.0}
        chambers = {'a': 'House', 'b': 'House', 'c': 'Senate', 'd': 'Senate'}
        out = PAG.within_chamber_percentile(values, chambers)
        # Bottom of each chamber is 0.0 and top is 1.0 -- the House member with
        # the lowest value is NOT compared against the Senate.
        self.assertEqual(out, {'a': 0.0, 'b': 1.0, 'c': 0.0, 'd': 1.0})


class ProductForm(unittest.TestCase):
    """R1: the board value is factor x (0.80 + 0.20 x grade percentile)."""

    def test_score_is_the_ratified_product(self):
        scores = TU.primacy_scores({'A': {'leg': 0.8, 'press': 1.0}}, {'A': 0.5},
                                   mode='per_area_v1', grade_form='whole', grades={'A': 1.0})
        self.assertAlmostEqual(scores['A'], 0.5)
        scores = TU.primacy_scores({'A': {'leg': 0.8, 'press': 1.0}}, {'A': 0.5},
                                   mode='per_area_v1', grade_form='whole', grades={'A': 0.0})
        self.assertAlmostEqual(scores['A'], 0.4)
        scores = TU.primacy_scores({'A': {'leg': 0.8, 'press': 1.0}}, {'A': 0.5},
                                   mode='per_area_v1', grade_form='whole', grades={'A': 0.5})
        self.assertAlmostEqual(scores['A'], 0.45)

    def test_factor_mode_is_untouched_by_the_new_parameter(self):
        scores = TU.primacy_scores({'A': {'leg': 0.8}}, {'A': 0.5}, mode='factor',
                                   grades={'A': 0.0})
        self.assertAlmostEqual(scores['A'], 0.5)

    def test_rankable_roster_is_identical_under_all_three_modes(self):
        pcts = {'A': {'leg': 0.8}, 'B': {'leg': 0.2}, 'C': {'press': 1.0}}
        factors = {'A': 0.5, 'B': 0.9, 'C': 0.7}
        grades = {'A': 0.1, 'B': 0.2, 'C': 0.3}
        self.assertEqual(
            set(TU.primacy_scores(pcts, factors, mode='factor')),
            set(TU.primacy_scores(pcts, factors, mode='per_area_v1',
                                  grades=grades, baseline=0.5)))
        self.assertEqual(
            set(TU.primacy_scores(pcts, factors, mode='legxfactor')),
            set(TU.primacy_scores(pcts, factors, mode='per_area_v1',
                                  grades=grades, baseline=0.5)))


