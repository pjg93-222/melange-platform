    def test_provenance_hashes_every_input_and_matches_disk(self):
        """Every declared input is hashed, and the hash IS the file on disk.

        ONE narrow, self-expiring exception: data/engine/primacy_factors.json may
        lag when the grade artifact was written BEFORE the factor was rebuilt.
        That was the shipped chain order until 2026-09-16 -- per_area_grade.py ran
        as a standalone run_pipeline step and build_primacy_surfaces'
        ENGINE_INPUT_STEPS re-ran engine/primacy_factors.py afterwards. The grade
        now runs INSIDE ENGINE_INPUT_STEPS immediately after the factor, so from
        the next chain run the artifact is newer than the factor and this branch
        is unreachable: the test then enforces exact equality with no exception.
        A lag in any OTHER input is a hard failure, and the orphan check below
        guards the harm the lag could actually do."""
        doc = self.document()
        self.assertEqual(set(doc['inputs']), set(PAG.INPUT_FILES))
        artifact_mtime = os.path.getmtime(_ARTIFACT)
        for relative, recorded in sorted(doc['inputs'].items()):
            self.assertEqual(len(recorded), 64, relative)
            path = os.path.join(ROOT, *relative.split('/'))
            if not os.path.exists(path):
                continue
            if recorded == PAG.sha256_of(path):
                continue
            self.assertEqual(
                relative, 'data/engine/primacy_factors.json',
                '%s moved since the grade was built' % relative)
            self.assertGreater(
                os.path.getmtime(path), artifact_mtime,
                'primacy_factors.json differs from the recorded hash but is NOT '
                'newer than the grade artifact, so the documented one-cycle lag '
                'does not explain it: rebuild fec/engine/per_area_grade.py')

