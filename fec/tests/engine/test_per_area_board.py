@unittest.skipUnless(os.path.exists(_ARTIFACT) and os.path.exists(_RANKS),
                     'per_area_grade.json or ranks_python.json absent')
class BoardModes(unittest.TestCase):
    """The revert switch, asserted by SELF-CONSISTENCY against the same live
    inputs. It used to be asserted against member_desk_bundle.json as the "board
    of record" -- but the bundle is now itself a per_area_v1 build, so that
    comparison is false by construction and was retired on 2026-09-16."""

    @classmethod
    def setUpClass(cls):
        cls.members = sorted(TU.load_per_area_grade(ROOT))

    def factor_board_recomputed(self):
        """Re-seat factor mode from ranks + factors ALONE -- the grade artifact is
        never opened -- through the same gate and ladder tier_util uses."""
        with open(_RANKS, encoding='utf-8') as handle:
            pcts = json.load(handle).get('pcts', {})
        factors = TU.load_primacy_ranked(ROOT)
        scores = TU.primacy_scores(pcts, factors, mode='factor')
        rankable = [member for member in self.members if member in scores]
        order = sorted(rankable, key=lambda member: (-scores[member], member))
        overrides = TU.load_tier_overrides()
        order = TU.apply_tier_overrides(order, overrides,
                                        positions=TU.load_tier_positions())
        order = TU.apply_evidence_floor(order, TU.load_primacy_cu_credit(ROOT),
                                        exempt=set(overrides))
        order, _detail = TU.apply_conduct_ladder(
            order, TU.load_open_breaches(ROOT), TU.load_delivery_credit(ROOT))
        first, second, third = 13, 37, 85
        return {member: (1 if index < first else 2 if index < second
                         else 3 if index < third else 0,
                         index + 1)
                for index, member in enumerate(order)}

    def test_factor_mode_reproduces_the_factor_seating_of_the_same_inputs(self):
        tier, rank = TU.legislative_press_tiers(self.members, root=ROOT,
                                                mode='factor')
        rebuilt = {member: (tier[member], rank[member])
                   for member in self.members}
        self.assertEqual(rebuilt, self.factor_board_recomputed())

    def test_factor_mode_never_reads_the_grade(self):
        """The revert must survive a grade artifact that is missing or corrupt --
        otherwise PRIMACY_BOARD=factor is not a revert. Negative control: make
        the loader explode, and factor mode must not notice."""
        original = TU.load_per_area_grade

        def explode(*args, **kwargs):
            raise AssertionError('factor mode read the per-area grade')

        TU.load_per_area_grade = explode
        try:
            tier, _rank = TU.legislative_press_tiers(self.members, root=ROOT,
                                                     mode='factor')
        finally:
            TU.load_per_area_grade = original
        self.assertEqual(sum(1 for member in self.members if tier[member] == 1),
                         13)

    def test_per_area_mode_actually_moves_the_board(self):
        """Negative control: if the dial did nothing, every test above would
        still pass while the board silently stayed factor-only. Asserted as
        'at least one tier moves' -- the COUNT (55 gated / 84 ungated on the
        2026-09-15 sweep) is a chain-regenerated number and lives on the fixture
        plane."""
        factor_tier, _fr = TU.legislative_press_tiers(self.members, root=ROOT,
                                                      mode='factor')
        area_tier, _ar = TU.legislative_press_tiers(self.members, root=ROOT,
                                                    mode='per_area_v1')
        self.assertNotEqual(area_tier, factor_tier)
        changed = sum(1 for member in self.members
                      if area_tier[member] != factor_tier[member])
        self.assertGreater(changed, 0)
        self.assertEqual(
            sum(1 for member in self.members if area_tier[member] == 1), 13)

    def test_reporting_rank_does_not_move(self):
        """The board is not the reporting rank. compute_pillars writes
        ranks_python.json from the workbook pillars and reads no board artifact,
        so flipping the dial must leave the file byte-identical and the rank
        producer must not reference the grade artifact."""
        with open(_RANKS, 'rb') as handle:
            before = hashlib.md5(handle.read()).hexdigest()
        TU.legislative_press_tiers(self.members, root=ROOT, mode='per_area_v1')
        with open(_RANKS, 'rb') as handle:
            after = hashlib.md5(handle.read()).hexdigest()
        self.assertEqual(before, after)
        with open(os.path.join(FEC, 'engine', 'compute_pillars.py'),
                  encoding='utf-8') as handle:
            pillars = handle.read()
        self.assertNotIn('per_area_grade', pillars)
        self.assertNotIn('PER_AREA_GRADE_PATH', pillars)


