"""Re-stamp the installed member-narratives artifact's basis_sha256 to the current evidence basis.

Why this exists: merge_member_narratives_v2.py fail-closes when the installed artifact's
basis_sha256 differs from the evidence ledger's. That guard exists so briefs written against a
stale ledger cannot be activated. On 2026-09-02 another lane regenerated
data/members/member_narrative_evidence_v4.json with a new basis while the portrait rewrite was in
flight. A drift check re-reviewed 60 previously-passing portraits against the NEW ledger and all 60
still passed, indicating member-level values did not move. Paul authorised the override explicitly.

This script only rewrites that one field, takes a timestamped backup first, and records the reason
in the artifact's provenance. It does not touch brief text. Run it, then run
merge_member_narratives_v2.py --activate.
"""
import datetime
import json
import os
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ARTIFACT = ROOT / "member_narratives_v2.json"
EVIDENCE = ROOT / "data" / "members" / "member_narrative_evidence_v4.json"
WORK = ROOT / "data" / "members" / "member_narratives_v2_work"

REASON = (
    "Evidence ledger regenerated by another lane 2026-09-02 20:36 with a new basis while the "
    "portrait rewrite was in flight. Drift check: 60 of 60 previously-passing portraits re-reviewed "
    "against the new ledger still passed, so member values did not move. Re-stamped on Paul's "
    "explicit override so the Opus-repaired briefs could be activated."
)


def main() -> int:
    artifact = json.loads(ARTIFACT.read_text(encoding="utf-8"))
    evidence = json.loads(EVIDENCE.read_text(encoding="utf-8"))
    old = artifact.get("basis_sha256")
    new = evidence.get("basis_sha256")
    if not new:
        raise SystemExit("evidence ledger has no basis_sha256")
    if old == new:
        print("basis already matches (%s); nothing to do" % str(new)[:16])
        return 0

    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    WORK.mkdir(parents=True, exist_ok=True)
    backup = WORK / ("member_narratives_v2.pre_basis_restamp_%s.json" % stamp)
    shutil.copy2(ARTIFACT, backup)

    artifact["basis_sha256"] = new
    artifact.setdefault("provenance", {})["basis_restamp"] = {
        "date": stamp,
        "old_basis": old,
        "new_basis": new,
        "reason": REASON,
    }
    temporary = ARTIFACT.with_suffix(".json.tmp")
    temporary.write_text(json.dumps(artifact, ensure_ascii=False, indent=1), encoding="utf-8")
    os.replace(temporary, ARTIFACT)

    print("re-stamped basis %s -> %s" % (str(old)[:16], str(new)[:16]))
    print("backup: %s" % backup)
    print("next: python fec/members/merge_member_narratives_v2.py --activate")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
